#!/usr/bin/env python3
"""Inter Tight for QUADRILLE's screens: static instances of the variable font, subset, embedded as C arrays.

    python3 tools/make_fonts.py [--src PATH/InterTight[wght].ttf]

stb_truetype (inside plutovg) cannot pick a variable axis, so this makes one static instance per weight with
fontTools' instancer (wght 200, 300, 400, 500, 600, 700), subsets each to what the screens draw (ASCII, Latin-1 and
a few symbols: · × → – — ° ± ½ ¼), drops hinting and layout tables (stb_truetype reads neither), and writes

    assets/fonts/InterTight-<weight>.ttf    the instances (committed, with OFL.txt beside them)
    core/gfx/fonts_gen.h                    the same bytes as C arrays (the core embeds them; it never reads a file)

The source is ChoralRoot's copy of the variable font (SIL OFL 1.1, The Inter Project Authors). Deterministic: the
same source gives the same bytes (the instances' timestamps are fixed).
"""
import argparse
import io
import os
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_SRC = os.path.join(ROOT, '..', 'ChoralRootFM1', 'assets', 'fonts', 'InterTight[wght].ttf')
WEIGHTS = [200, 300, 400, 500, 600, 700]
# ASCII, Latin-1 (· × ° ± ½ ¼ are in it), the dashes and the arrow
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x2013, 0x2014, 0x2192, 0x2026, 0x2212]


def make_instance(src, weight):
    font = TTFont(src)
    inst = instancer.instantiateVariableFont(font, {'wght': weight}, inplace=False)
    opts = subset.Options()
    opts.layout_features = []          # no GSUB / GPOS: stb_truetype does not read them
    opts.hinting = False
    opts.notdef_outline = True
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]   # copyright, names, licence
    opts.name_languages = [0x409]
    opts.drop_tables += ['DSIG', 'GDEF', 'GPOS', 'GSUB', 'STAT', 'meta']
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(inst)
    inst['head'].created = inst['head'].modified = 0xE1E6D200   # fixed (2023-12): reproducible bytes
    inst.recalcTimestamp = False
    out = io.BytesIO()
    inst.save(out, reorderTables=True)
    return out.getvalue()


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 20]) + ',')
    return 'static const unsigned char %s[%d] QD_XDATA(%s) = {\n%s\n};\n' % (name, len(data), name, '\n'.join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--src', default=DEFAULT_SRC, help='the variable Inter Tight TTF')
    a = ap.parse_args()
    src = os.path.abspath(a.src)
    if not os.path.exists(src):
        sys.exit('make_fonts: no ' + src)
    fonts_dir = os.path.join(ROOT, 'assets', 'fonts')
    os.makedirs(fonts_dir, exist_ok=True)
    parts = []
    for w in WEIGHTS:
        data = make_instance(src, w)
        with open(os.path.join(fonts_dir, 'InterTight-%d.ttf' % w), 'wb') as f:
            f.write(data)
        parts.append((w, data))
        print('InterTight-%d.ttf: %d bytes' % (w, len(data)))
    h = ['/* GENERATED by tools/make_fonts.py: do not edit. */',
         '/* Inter Tight (SIL Open Font License 1.1, Copyright 2022 The Inter Project Authors,',
         ' * https://github.com/rsms/inter-tight; assets/fonts/OFL.txt): static instances of the variable font,',
         ' * subset to ASCII, Latin-1 and a few symbols. Included once, by core/gfx/qd_gfx_plutovg.c. */',
         '#pragma once', '#include "../qd_config.h"                   /* (P2.1b: QD_XDATA, the data region on the device) */', '']
    # P2.1: at the device's sizes (QD_FONTS3, core/qd_config.h) only 300, 500 and 700 (the others map to the nearest)
    three = (300, 500, 700)
    for w, data in parts:
        if w not in three:
            h.append('#ifndef QD_FONTS3')
        h.append(c_array('qd_font_inter_tight_%d' % w, data))
        if w not in three:
            h.append('#endif')
    h.append('static const struct { int weight; const unsigned char *data; unsigned int len; } qd_fonts_gen[] = {')
    for w, data in parts:
        if w not in three:
            h.append('#ifndef QD_FONTS3')
        h.append('    {%d, qd_font_inter_tight_%d, %d},' % (w, w, len(data)))
        if w not in three:
            h.append('#endif')
    h.append('};')
    h.append('#ifdef QD_FONTS3')
    ws3 = [w for w, _ in parts if w in three]
    ws = [w for w, _ in parts]
    h.append("#define QD_FONTS_GEN_N %d                /* (P2.1: the device's three weights, 300 500 700) */" % len(ws3))
    h.append('#define QD_FONTS_GEN_500 %d              /* (the 500\'s place: the tools\' sheet captions) */' %
             ws3.index(500))
    h.append('#else')
    h.append('#define QD_FONTS_GEN_N %d' % len(parts))
    h.append('#define QD_FONTS_GEN_500 %d' % ws.index(500))
    h.append('#endif')
    h.append('')
    out = os.path.join(ROOT, 'core', 'gfx', 'fonts_gen.h')
    with open(out, 'w') as f:
        f.write('\n'.join(h))
    print('core/gfx/fonts_gen.h: %d fonts, %d bytes of font data' % (len(parts), sum(len(d) for _, d in parts)))


if __name__ == '__main__':
    main()

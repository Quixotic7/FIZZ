"""The stats fields' names (2026-10-26, the flash diet): firmware/app/app.c sends each counter as "<id>:<value>"; the
ids are the FZN_* identifiers it uses, in first-seen order, so the names cost the firmware nothing. This writes the
enum (firmware/app/fz_stats_names.h) and the list the host tool prints them with (firmware/tools/
fizz_stats_names.py). --check: fail when either is stale (make -C tools stats-names-check, in make test)."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SRC = os.path.join(ROOT, "firmware", "app", "app.c")
H = os.path.join(ROOT, "firmware", "app", "fz_stats_names.h")
PY = os.path.join(ROOT, "firmware", "tools", "fizz_stats_names.py")


def main():
    src = open(SRC).read()
    names = []
    for m in re.finditer(r"\bFZN_([A-Za-z0-9_]+)\b", src):
        n = m.group(1)
        if n in ("NONE", "MORE", "N") or n in names:
            continue
        names.append(n)
    h = ["/* generated by tools/gen_stats_names.py from firmware/app/app.c: do not edit (make -C tools stats-names) */",
         "#ifndef FZ_STATS_NAMES_H", "#define FZ_STATS_NAMES_H",
         "enum { FZN_NONE, FZN_MORE,"]
    h += ["       FZN_%s," % n for n in names]
    h += ["       FZN_N };", "#endif", ""]
    py = ["# generated by tools/gen_stats_names.py from firmware/app/app.c: do not edit (make -C tools stats-names)",
          "NAMES = [\"\", \",\"] + ["] + ['    "%s",' % n for n in names] + ["]", ""]
    h, py = "\n".join(h), "\n".join(py)
    if "--check" in sys.argv:
        ok = os.path.exists(H) and open(H).read() == h and os.path.exists(PY) and open(PY).read() == py
        print("stats-names-check: " + ("the names are app.c's" if ok else "STALE: make -C tools stats-names"))
        return 0 if ok else 1
    open(H, "w").write(h)
    open(PY, "w").write(py)
    print("stats names: %d fields -> %s, %s" % (len(names), os.path.relpath(H, ROOT), os.path.relpath(PY, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""The SENDS page's cat (2026-10-26, the owner's vector art/cat-sends.svg; mockups/fizz-sends-cat.html) as point tables.

    python3 tools/gen_cat.py        # writes core/ui/ui_cat.h (and the MASTER head)

Each drawn path of the SVG is placed on the screen (its ear tips at y 22, its chin at 176, centred at x 120: the
big cat's, fizz-sends-cat2.html) and written in 1/8 px as int16: a part is [subpaths, then for each: segments, x0, y0, then each
segment's cubic c1, c2, end]. Lines become cubics (the controls at their thirds); a closed subpath gets its closing
line. The ears are written as their triangles (the base's two corners, the tip), the lens's left and right as its x
range. Only the parts the page draws (the SVG's black backdrop and its masks are not).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
SVG = os.path.join(REPO, 'art', 'cat-sends.svg')
OUT = os.path.join(REPO, 'core', 'ui', 'ui_cat.h')
NAMES = ['OUTLINE', 'VISOR', 'LENS', 'EAR_L', None, 'EAR_R',
         'WH_L1', 'WH_L2', 'WH_L3', 'WH_R1', 'WH_R2', 'WH_R3', 'NOSE', 'MOUTH1', 'MOUTH2']
SC, CX, TOP, X0, Y0 = 0.197, 542.5, 58.0, 120.0, 22.0   # the SVG's units to the screen's px (fizz-sends-cat2.html)


def scr(x, y):
    return X0 + (x - CX) * SC, Y0 + (y - TOP) * SC


def parse(d, tx, ty):
    """the path's subpaths, each a list of cubics ((x0, y0), c1, c2, end) in the SVG's units"""
    toks = re.findall(r'[MLCZ]|-?\d+(?:\.\d+)?(?:e-?\d+)?', d)
    subs, cur, start, pt, i, cmd = [], None, None, None, 0, None
    while i < len(toks):
        t = toks[i]
        if t in 'MLCZ':
            cmd = t
            i += 1
            if cmd == 'Z':
                if pt != start:
                    cur.append(line(pt, start))
                pt = start
            continue
        n = [float(v) for v in toks[i:i + (6 if cmd == 'C' else 2)]]
        i += len(n)
        if cmd == 'M':
            cur = []
            subs.append(cur)
            pt = start = (n[0] + tx, n[1] + ty)
            cmd = 'L'                                    # (more pairs after M are lines)
        elif cmd == 'L':
            p = (n[0] + tx, n[1] + ty)
            if p != pt:
                cur.append(line(pt, p))
            pt = p
        else:
            c1, c2, p = (n[0] + tx, n[1] + ty), (n[2] + tx, n[3] + ty), (n[4] + tx, n[5] + ty)
            cur.append((pt, c1, c2, p))
            pt = p
    return [s for s in subs if s]


def line(a, b):
    return (a, (a[0] + (b[0] - a[0]) / 3, a[1] + (b[1] - a[1]) / 3), (a[0] + 2 * (b[0] - a[0]) / 3, a[1] + 2 * (b[1] - a[1]) / 3), b)


def q(p):
    x, y = scr(*p)
    return [round(x * 8), round(y * 8)]


def attr(a, k):
    m = re.search(r'\b%s="([^"]*)"' % k, a)
    return m.group(1) if m else None


s = open(SVG).read()
paths = re.findall(r'<path\s([^>]*)/>', s[s.index('</defs>'):])[1:]      # [0]: the black backdrop
assert len(paths) == len(NAMES), len(paths)
out = ['/* SPDX-License-Identifier: MPL-2.0',
       ' * generated by tools/gen_cat.py from art/cat-sends.svg (the owner\'s cat): do not edit.',
       ' * A part: [subpaths, then each: segments, x0, y0, then each segment\'s c1x, c1y, c2x, c2y, x, y], in 1/8 px. */',
       '#pragma once', '#include <stdint.h>', '']
total = 0
for name, a in zip(NAMES, paths):
    if not name:
        continue
    tx = ty = 0.0
    t = attr(a, 'transform')
    if t:
        m = [float(v) for v in re.findall(r'-?[\d.]+', t)]
        tx, ty = m[4], m[5]
    subs = parse(attr(a, 'd'), tx, ty)
    if name.startswith('EAR'):                       # the ear as its triangle: the base's corners, the tip
        pts = [subs[0][0][0]] + [c[3] for c in subs[0]]
        tip = min(pts, key=lambda p: p[1])
        base_a, base_b = subs[0][0][0], subs[0][0][3]
        vals = q(base_a) + q(base_b) + q(tip)
        out.append('static const int16_t CAT_%s[6] = {%s};   /* base a, base b, tip */' % (name, ', '.join(map(str, vals))))
        total += 12
        continue
    vals = [len(subs)]
    for sp in subs:
        vals += [len(sp)] + q(sp[0][0])
        for c in sp:
            vals += q(c[1]) + q(c[2]) + q(c[3])
    if name == 'LENS':
        xs = [scr(p[0], 0)[0] for sp in subs for c in sp for p in c]
        out.append('#define CAT_LENS_X0 %.2ff   /* the lens\'s left and right, px (REVERB fills it from the left) */' % min(xs))
        out.append('#define CAT_LENS_X1 %.2ff' % max(xs))
        ys = [scr(0, p[1])[1] for sp in subs for c in sp for p in c]
        out.append('#define CAT_LENS_Y0 %.2ff   /* .. its top and bottom, px (the glint, the flash) */' % min(ys))
        out.append('#define CAT_LENS_Y1 %.2ff' % max(ys))
    if name == 'OUTLINE':
        xs = [scr(p[0], 0)[0] for sp in subs for c in sp for p in (c[0], c[3])]
        out.append('#define CAT_OUT_X0 %.2ff    /* the outline\'s left and right, px (its colours run across it) */' % min(xs))
        out.append('#define CAT_OUT_X1 %.2ff' % max(xs))
    body = ', '.join(map(str, vals))
    out.append('static const int16_t CAT_%s[%d] = {%s};' % (name, len(vals), body))
    total += 2 * len(vals)
# the MASTER page's head (2026-10-26, the owner's art/filter-head.svg, facing left; mockups/fizz-master-heads2.html):
# 118 px tall, in its own frame (its box's top left at 0, 0), 1/8 px; the page places it and mirrors the HIGH one
hs = open(os.path.join(REPO, 'art', 'filter-head.svg')).read()
hd = re.search(r'<path d="([^"]*)"', hs).group(1)
hn = [float(v) for v in re.findall(r'-?\d+(?:\.\d+)?', hd)]
hx0, hy0, hx1, hy1 = min(hn[0::2]), min(hn[1::2]), max(hn[0::2]), max(hn[1::2])
hsc = 118.0 / (hy1 - hy0)
hsubs = parse(hd, 0.0, 0.0)
hv = [len(hsubs)]
hq = lambda p: [round((p[0] - hx0) * hsc * 8), round((p[1] - hy0) * hsc * 8)]
for sp in hsubs:
    hv += [len(sp)] + hq(sp[0][0])
    for c in sp:
        hv += hq(c[1]) + hq(c[2]) + hq(c[3])
out.append('#define HEAD_W %.2ff     /* the MASTER head, px (art/filter-head.svg, facing left) */' % ((hx1 - hx0) * hsc))
out.append('#define HEAD_H 118.f')
out.append('static const int16_t CAT_HEAD[%d] = {%s};' % (len(hv), ', '.join(map(str, hv))))
total += 2 * len(hv)
out.append('')
open(OUT, 'w').write('\n'.join(out))
print('wrote', os.path.relpath(OUT, REPO), total, 'B of tables')

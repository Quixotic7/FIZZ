/* gen_fast_font: the fast drawing's text (core/gfx/qd_gfx_fast.c) from the Inter Tight instances FIZZ already ships
 * (core/gfx/fonts_gen.h, the device's three weights 300 500 700):
 *
 *   gen_fast_font OUT.h        (tools/gfx_fast.mk: make -f gfx_fast.mk fast-font)
 *
 * It writes one header, core/gfx/qd_fast_font.h, with
 *   - the charset (QF_NG glyphs: .notdef, ASCII 0x20..0x7E, and the few symbols the screens draw);
 *   - per weight: the advances (font units: qd_text_width is the same float sum plutovg makes) and the outlines
 *     (TrueType's quadratic contours, delta-coded, ~4 bytes a point) for any size or transform;
 *   - glyph atlases (4-bit alpha) at the sizes and weights the screens draw most (the table ATLAS below, measured over
 *     render_frames at the device's sizes), each glyph rasterised by plutovg itself with its origin on a whole pixel,
 *     so a glyph drawn from an atlas at a whole pixel is plutovg's to the 4-bit level.
 * Everything big is QD_XDATA (the device's data region). Deterministic: the same fonts give the same bytes. */
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define STBTT_STATIC
#define STB_TRUETYPE_IMPLEMENTATION
#include "plutovg-stb-truetype.h"
#include "plutovg.h"

#define QD_FONTS3 1
#include "fonts_gen.h"

/* the charset: .notdef first, then ASCII, then the symbols (· × ± ° – — − … →) */
static const uint32_t EXTRA[] = {0xB0, 0xB1, 0xB7, 0xD7, 0x2013, 0x2014, 0x2026, 0x2192, 0x2212};
#define NEXTRA ((int)(sizeof EXTRA / sizeof EXTRA[0]))
#define NG (1 + 95 + NEXTRA)
static uint32_t CP[NG];

/* the atlases: (px, weight). Measured over render_frames at the device's sizes (the calls a run: 12 px 700 151k,
 * 13/500 50k, 12/500 24k, 18/500 13k, 15/500 13k, 24/300 12k, 14/500 12k, 19/500 6k, 13/700 3k, 16/500 3k ..) and
 * kept to what the data region holds: the outlines draw every other size about as fast (tools/bench_gfx.c: all text
 * from the outlines costs 5..25 % more a frame), and exactly as plutovg does. Text at any other size, under a scale
 * that is not uniform, or turned, is drawn from the outlines */
static const struct { int px, w; } ATLAS[] = {                      /* (2026-10-26: the 500s at 300, the owner's choice) */
    {12, 300}, {12, 700}, {13, 300}, {13, 700}, {14, 300}, {15, 300}, {16, 300}, {18, 300},
};
/* the device's weights (2026-10-26, the flash diet): 300 and 700 of fonts_gen.h's 300 500 700 (its indexes); 400
 * and 500 read light (qd_gfx_fast.c weight_index), as the owner chose over dropping the light one */
#define NW 2
static const int FW[NW] = {0, 2};
#define NATLAS ((int)(sizeof ATLAS / sizeof ATLAS[0]))

static FILE *out;
static unsigned long total_xdata, total_const;

static void bytes(const char *type, const char *name, const uint8_t *b, size_t n, int xdata)
{
    size_t i;
    fprintf(out, "static const %s %s[%lu]%s%s%s = {", type, name, (unsigned long)n, xdata ? " QD_XDATA(" : "",
            xdata ? name : "", xdata ? ")" : "");
    for (i = 0; i < n; i++)
        fprintf(out, "%s%u,", i % 24 ? "" : "\n    ", b[i]);
    fprintf(out, "\n};\n");
    if (xdata)
        total_xdata += n;
    else
        total_const += n;
}

/* ---- the outlines: per glyph, a varint of the vertex count, the types two bits each (0 move, 1 line, 2 quadratic),
 * then the coordinates as zigzag varints of the change from the last coordinate on the same axis (a quadratic's
 * control point, then its end) */
static uint8_t ob[1 << 18];
static size_t on;
static void put_v(uint32_t v)
{
    while (v >= 128) {
        ob[on++] = (uint8_t)(v | 128);
        v >>= 7;
    }
    ob[on++] = (uint8_t)v;
}
static void put_z(int v) { put_v(v < 0 ? ((uint32_t)(-v) << 1) - 1u : (uint32_t)v << 1); }

int main(int argc, char **argv)
{
    int w, i, a;
    if (argc < 2) {
        fprintf(stderr, "usage: gen_fast_font OUT.h\n");
        return 2;
    }
    CP[0] = 0xFFFFFFFFu;                                /* (.notdef: glyph 0) */
    for (i = 0; i < 95; i++)
        CP[1 + i] = 0x20u + (uint32_t)i;
    for (i = 0; i < NEXTRA; i++)
        CP[96 + i] = EXTRA[i];
    out = fopen(argv[1], "w");
    if (!out) {
        fprintf(stderr, "gen_fast_font: cannot write %s\n", argv[1]);
        return 1;
    }
    fprintf(out, "/* SPDX-License-Identifier: MPL-2.0 (the code); the glyphs: Inter Tight, SIL OFL 1.1, The Inter Project "
                 "Authors (assets/fonts/OFL.txt) */\n/* generated by tools/gen_fast_font.c from core/gfx/fonts_gen.h: "
                 "do not edit (make -C tools -f Makefile -f gfx_fast.mk fast-font) */\n#pragma once\n#include <stdint.h>\n"
                 "#include \"../qd_config.h\"\n\n#define QF_NG %d\n#define QF_NW %d\n#define QF_NATLAS %d\n"
                 "static const uint16_t QF_WEIGHT[QF_NW] = {%d, %d};\n",
            NG, NW, NATLAS, qd_fonts_gen[FW[0]].weight, qd_fonts_gen[FW[1]].weight);
    fprintf(out, "/* the charset after .notdef (glyph 0): ASCII 0x20..0x7E are glyphs 1..95 */\n"
                 "static const uint16_t QF_EXTRA[%d] = {", NEXTRA);
    for (i = 0; i < NEXTRA; i++)
        fprintf(out, "0x%04X%s", (unsigned)EXTRA[i], i + 1 < NEXTRA ? ", " : "};\n");

    /* ---- per weight: units per em, advances, outlines */
    {
        int upem[NW];
        int16_t adv[NW][NG];
        uint32_t off[NW][NG + 1];
        stbtt_fontinfo fi[NW];
        char name[64];
        for (w = 0; w < NW; w++) {
            if (!stbtt_InitFont(&fi[w], qd_fonts_gen[FW[w]].data, 0))
                return 1;
            upem[w] = ttUSHORT(fi[w].data + fi[w].head + 18);
            on = 0;
            for (i = 0; i < NG; i++) {
                const int gi = i ? stbtt_FindGlyphIndex(&fi[w], (int)CP[i]) : 0;
                stbtt_vertex *v;
                int n, k, adv_i, lsb, px = 0, py = 0;
                if (i && !gi)
                    fprintf(stderr, "gen_fast_font: U+%04X not in weight %d (.notdef)\n", (unsigned)CP[i],
                            qd_fonts_gen[w].weight);
                stbtt_GetGlyphHMetrics(&fi[w], gi, &adv_i, &lsb);
                adv[w][i] = (int16_t)adv_i;
                off[w][i] = (uint32_t)on;
                n = stbtt_GetGlyphShape(&fi[w], gi, &v);
                put_v((uint32_t)n);
                for (k = 0; k < n; k += 4) {
                    int b = 0, j;
                    for (j = 0; j < 4 && k + j < n; j++) {
                        const int t = v[k + j].type == STBTT_vmove ? 0 : v[k + j].type == STBTT_vline ? 1 : 2;
                        if (v[k + j].type == STBTT_vcubic) {
                            fprintf(stderr, "gen_fast_font: a cubic in a TrueType glyph\n");
                            return 1;
                        }
                        b |= t << (2 * j);
                    }
                    ob[on++] = (uint8_t)b;
                }
                for (k = 0; k < n; k++) {
                    if (v[k].type == STBTT_vcurve) {
                        put_z(v[k].cx - px), put_z(v[k].cy - py);
                        px = v[k].cx, py = v[k].cy;
                    }
                    put_z(v[k].x - px), put_z(v[k].y - py);
                    px = v[k].x, py = v[k].y;
                }
                stbtt_FreeShape(&fi[w], v);
            }
            off[w][NG] = (uint32_t)on;
            snprintf(name, sizeof name, "qf_outline_%d", qd_fonts_gen[FW[w]].weight);
            bytes("uint8_t", name, ob, on, 1);
            printf("outlines %d: %lu B\n", qd_fonts_gen[FW[w]].weight, (unsigned long)on);
        }
        fprintf(out, "static const uint16_t QF_UPEM[QF_NW] = {%d, %d};\n", upem[0], upem[1]);
        fprintf(out, "static const int16_t QF_ADV[QF_NW][QF_NG] QD_XDATA(QF_ADV) = {");
        for (w = 0; w < NW; w++) {
            fprintf(out, "\n    {");
            for (i = 0; i < NG; i++)
                fprintf(out, "%d%s", adv[w][i], i + 1 < NG ? "," : "},");
        }
        fprintf(out, "\n};\nstatic const uint16_t QF_OOFF[QF_NW][QF_NG + 1] QD_XDATA(QF_OOFF) = {");
        for (w = 0; w < NW; w++) {
            fprintf(out, "\n    {");
            for (i = 0; i <= NG; i++) {
                if (off[w][i] > 65535u)
                    return 1;
                fprintf(out, "%u%s", (unsigned)off[w][i], i < NG ? "," : "},");
            }
        }
        fprintf(out, "\n};\nstatic const uint8_t *const QF_OUTLINE[QF_NW] = {qf_outline_%d, qf_outline_%d};\n",
                qd_fonts_gen[FW[0]].weight, qd_fonts_gen[FW[1]].weight);
        total_const += sizeof adv + (unsigned long)NW * 2u * (NG + 1);
    }

    /* ---- the atlases: each glyph rasterised by plutovg at a whole-pixel origin, its alpha in 4 bits (two pixels a
     * byte, rows packed), trimmed to its ink */
    fprintf(out, "\n/* an atlas glyph: its ink's box from the pen (x right, y down from the baseline), its 4-bit alpha "
                 "at off (w * h nibbles, the low nibble first) */\ntypedef struct { int8_t x, y; uint8_t w, h; uint16_t "
                 "off; } qf_ag;\ntypedef struct { uint8_t px, wi; const qf_ag *g; const uint8_t *bits; } qf_atlas;\n");
    {
        plutovg_font_face_t *face[NW];
        static uint8_t bits[1 << 17];
        for (w = 0; w < NW; w++)
            face[w] = plutovg_font_face_load_from_data(qd_fonts_gen[FW[w]].data, qd_fonts_gen[FW[w]].len, 0, NULL, NULL);
        for (a = 0; a < NATLAS; a++) {
            const int wi = ATLAS[a].w == 300 ? 0 : 1;
            const float px = (float)ATLAS[a].px;
            struct { int x, y, w, h, off; } rec[NG];
            size_t nb = 0;
            char name[64];
            stbtt_fontinfo fi;
            stbtt_InitFont(&fi, qd_fonts_gen[FW[wi]].data, 0);
            for (i = 0; i < NG; i++) {
                const int gi = i ? stbtt_FindGlyphIndex(&fi, (int)CP[i]) : 0;
                const float sc = stbtt_ScaleForMappingEmToPixels(&fi, px);
                int x1, y1, x2, y2, l, t, r, b, W, H, x, y, ix0, iy0, ix1, iy1;
                plutovg_surface_t *s;
                plutovg_canvas_t *c;
                const uint8_t *d;
                int stride;
                if (!stbtt_GetGlyphBox(&fi, gi, &x1, &y1, &x2, &y2)) {
                    rec[i].x = rec[i].y = rec[i].w = rec[i].h = 0, rec[i].off = (int)nb;
                    continue;
                }
                l = (int)floorf((float)x1 * sc) - 2, r = (int)ceilf((float)x2 * sc) + 2;
                t = (int)floorf(-(float)y2 * sc) - 2, b = (int)ceilf(-(float)y1 * sc) + 2;
                W = r - l, H = b - t;
                s = plutovg_surface_create(W, H);
                c = plutovg_canvas_create(s);
                plutovg_canvas_set_font(c, face[wi], px);
                plutovg_canvas_add_glyph(c, i ? CP[i] : 0xFFFFu, (float)-l, (float)-t);
                plutovg_canvas_set_rgba(c, 1.f, 1.f, 1.f, 1.f);
                plutovg_canvas_fill(c);
                d = plutovg_surface_get_data(s);
                stride = plutovg_surface_get_stride(s);
                ix0 = W, iy0 = H, ix1 = -1, iy1 = -1;
                for (y = 0; y < H; y++)
                    for (x = 0; x < W; x++)
                        if (((d[y * stride + 4 * x + 3]) * 15 + 127) / 255) {
                            ix0 = x < ix0 ? x : ix0, ix1 = x > ix1 ? x : ix1;
                            iy0 = y < iy0 ? y : iy0, iy1 = y > iy1 ? y : iy1;
                        }
                if (ix1 < 0) {
                    rec[i].x = rec[i].y = rec[i].w = rec[i].h = 0, rec[i].off = (int)nb;
                } else {
                    int k = 0;
                    rec[i].x = l + ix0, rec[i].y = t + iy0, rec[i].w = ix1 - ix0 + 1, rec[i].h = iy1 - iy0 + 1;
                    rec[i].off = (int)nb;
                    if (nb > 65535u || rec[i].w > 255 || rec[i].h > 255)
                        return 1;
                    for (y = iy0; y <= iy1; y++)
                        for (x = ix0; x <= ix1; x++, k++) {
                            const unsigned q = ((unsigned)d[y * stride + 4 * x + 3] * 15u + 127u) / 255u;
                            if (k & 1)
                                bits[nb + (size_t)(k >> 1)] |= (uint8_t)(q << 4);
                            else
                                bits[nb + (size_t)(k >> 1)] = (uint8_t)q;
                        }
                    nb += (size_t)((k + 1) >> 1);
                }
                plutovg_canvas_destroy(c);
                plutovg_surface_destroy(s);
            }
            snprintf(name, sizeof name, "qf_bits_%d_%d", ATLAS[a].px, ATLAS[a].w);
            bytes("uint8_t", name, bits, nb, 1);
            fprintf(out, "static const qf_ag qf_g_%d_%d[QF_NG] QD_XDATA(qf_g_%d_%d) = {", ATLAS[a].px, ATLAS[a].w,
                    ATLAS[a].px, ATLAS[a].w);
            for (i = 0; i < NG; i++)
                fprintf(out, "%s{%d,%d,%d,%d,%d},", i % 6 ? "" : "\n    ", rec[i].x, rec[i].y, rec[i].w, rec[i].h,
                        rec[i].off);
            fprintf(out, "\n};\n");
            total_xdata += (unsigned long)(6 * NG);
            printf("atlas %d px %d: %lu B + %d B\n", ATLAS[a].px, ATLAS[a].w, (unsigned long)nb, 6 * NG);
        }
        fprintf(out, "static const qf_atlas QF_ATLAS[QF_NATLAS] = {");
        for (a = 0; a < NATLAS; a++)
            fprintf(out, "\n    {%d, %d, qf_g_%d_%d, qf_bits_%d_%d},", ATLAS[a].px,
                    ATLAS[a].w == 300 ? 0 : 1, ATLAS[a].px, ATLAS[a].w, ATLAS[a].px,
                    ATLAS[a].w);
        fprintf(out, "\n};\n");
        for (w = 0; w < NW; w++)
            plutovg_font_face_destroy(face[w]);
    }
    fprintf(out, "/* sizes: %lu B of data region (QD_XDATA), %lu B of constants */\n", total_xdata, total_const);
    fclose(out);
    printf("gen_fast_font: %s: %lu B xdata, %lu B constants\n", argv[1], total_xdata, total_const);
    return 0;
}

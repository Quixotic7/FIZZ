"""The pack's 93 presets as factory presets 24..116 (core/seq/factory_tab.h), from tools/fizz_pack.h.

  python3 tools/gen_factory.py            writes core/seq/factory_tab.h
  python3 tools/gen_factory.py --check    exits 1 when the committed header is not what it would write

The table is sparse (flash is the binding limit: 93 plain patches are 21 KB):
  QD_FT_BASE   the 115 values each parameter has most often across the 93 (int16)
  QD_FT_DIFF   per preset, the values that differ from the base, as a byte stream: a byte id | 0x80 then one byte
               (the value fits int8), or a byte id then two (the value, int16 little endian); ids are 0..114
  QD_FT_OFF    where each preset's run starts in QD_FT_DIFF (QD_FT_N + 1 entries: the last is the end)
  QD_FT_META   tag (the pack's kind bit), pan (int8 as a byte), chorus, delay, reverb
  QD_FT_NAMES  the names, each ended by a NUL, in pack order
Only the table's first FIZZ_PACK_LIB entries are the pack (the others, sunfade-only.txt, are not factory presets)."""
import collections
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "fizz_pack.h"
OUT = ROOT / "core" / "seq" / "factory_tab.h"
NP = 115


def read_pack():
    src = SRC.read_text()
    lib = int(re.search(r"#define FIZZ_PACK_LIB (\d+)", src).group(1))
    rows = re.findall(r'\{"((?:[^"\\]|\\.)*)", (-?\d+), (-?\d+), (\d+), (\d+), (\d+), \{([^}]*)\}\}', src)
    pack = []
    for r in rows[:lib]:
        patch = [int(x) for x in r[6].split(",")]
        assert len(patch) == NP, r[0]
        name = bytes(r[0], "ascii").decode("unicode_escape")
        pack.append({"name": name, "tag": int(r[1]), "pan": int(r[2]), "sends": [int(r[3]), int(r[4]), int(r[5])],
                     "patch": patch})
    assert len(pack) == lib, (len(pack), lib)
    return pack


def encode(pack):
    base = [collections.Counter(p["patch"][i] for p in pack).most_common(1)[0][0] for i in range(NP)]
    diff, off = [], []
    for p in pack:
        off.append(len(diff))
        for i, v in enumerate(p["patch"]):
            if v == base[i]:
                continue
            if -128 <= v <= 127:
                diff += [i | 0x80, v & 0xFF]
            else:
                assert -32768 <= v <= 32767
                diff += [i, v & 0xFF, (v >> 8) & 0xFF]
    off.append(len(diff))
    assert len(diff) < 65536
    return base, diff, off


def decode(base, diff, off, j):
    """(the C decoder's rule, for the self-check)"""
    p, k = list(base), off[j]
    while k < off[j + 1]:
        b = diff[k]
        if b & 0x80:
            v = diff[k + 1]
            p[b & 0x7F] = v - 256 if v >= 128 else v
            k += 2
        else:
            v = diff[k + 1] | diff[k + 2] << 8
            p[b] = v - 65536 if v >= 32768 else v
            k += 3
    return p


def cstr(s):
    out = ""
    for ch in s:
        if ch in '"\\':
            out += "\\" + ch
        elif 0x20 <= ord(ch) < 0x7F:
            out += ch
        else:
            out += "\\%03o" % ord(ch)
    return out


def rows(vals, per, fmt="%d"):
    return ",\n".join("    " + ", ".join(fmt % v for v in vals[i:i + per]) for i in range(0, len(vals), per))


def generate():
    pack = read_pack()
    base, diff, off = encode(pack)
    for j, p in enumerate(pack):
        assert decode(base, diff, off, j) == p["patch"], p["name"]
        assert 0 < len(p["name"]) <= 12 and p["tag"] and not p["tag"] & ~0x7F, p["name"]
    names = "\n".join("    \"%s\\0\"" % cstr(p["name"]) for p in pack)   # (one literal each: "\\0" "1.." no octal)
    size = 2 * NP + 2 * len(off) + len(diff) + 5 * len(pack) + sum(len(p["name"]) + 1 for p in pack)
    meta = ",\n".join("    {%d, %d, %d, %d, %d}" % (p["tag"], p["pan"] & 0xFF, *p["sends"]) for p in pack)
    return f"""/* SPDX-License-Identifier: MPL-2.0
 * This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of the MPL was not
 * distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/. */
/* Generated by tools/gen_factory.py from tools/fizz_pack.h (the preset pack: presets/pack/drums.txt, pitched.txt):
 * do not edit. Factory presets 24..{23 + len(pack)}, sparse ({size} bytes): the base, each preset's values that differ
 * from it (id | 0x80, int8; or id, int16 LE), its tag, pan, chorus, delay, reverb, and its name. Included by
 * sounds.c only. */
#pragma once
#include <stdint.h>

#define QD_FT_N {len(pack)}
#define QD_FT_NP {NP}
static const int16_t QD_FT_BASE[QD_FT_NP] = {{
{rows(base, 16)}}};
static const uint16_t QD_FT_OFF[QD_FT_N + 1] = {{
{rows(off, 16)}}};
static const uint8_t QD_FT_DIFF[{len(diff)}] = {{
{rows(diff, 24)}}};
static const uint8_t QD_FT_META[QD_FT_N][5] = {{   /* tag, pan (int8), chorus, delay, reverb */
{meta}}};
static const char QD_FT_NAMES[] =
{names};
"""


def main():
    text = generate()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT}: not what tools/gen_factory.py writes (run it)")
        print(f"{OUT.name}: up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()

/* Manager P2: FIZZ's 110 sound values as the web manager's sound editor shows them, written from the core itself
 * (quad_voice.h: qd_quad_value_name, qd_quad_value_range, qd_quad_value_text, qd_quad_algo, the LFO destinations'
 * order), so the page's names, ranges and texts are the unit's own:
 *
 *   build/gen_values > ../site/manager/fizzvalues.js      (make -C tools values; make -C tools values-check compares)
 *
 * Each value: its name, min, max, default, and its texts as a rule plus the exceptions: "int" (the number), "ofs" (+n
 * above 0), "fix2" / "fix2s" (hundredths: 1.50, +1.50), or "list" (every text, an enumeration); "ex" the values whose
 * text differs from the rule (INF, OFF, NOTE ..). The generator checks the rule against every value's text. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "quad_voice.h"

static void rule_text(const char *rule, int v, char *out)
{
    const int a = v < 0 ? -v : v;
    if (!strcmp(rule, "ofs"))
        sprintf(out, v > 0 ? "+%d" : "%d", v);
    else if (!strcmp(rule, "fix2"))
        sprintf(out, "%d.%02d", a / 100, a % 100);
    else if (!strcmp(rule, "fix2s"))
        sprintf(out, "%c%d.%02d", v < 0 ? '-' : '+', a / 100, a % 100);
    else
        sprintf(out, "%d", v);
}

static void js_str(const char *s)
{
    putchar('"');
    for (; *s; s++) {
        if (*s == '"' || *s == '\\')
            putchar('\\');
        putchar(*s);
    }
    putchar('"');
}

int main(void)
{
    static const char *const RULES[4] = {"int", "ofs", "fix2", "fix2s"};
    int i, v, a, k;
    printf("// SPDX-License-Identifier: GPL-3.0-only\n");
    printf("// GENERATED by tools/gen_values.c from FIZZ's core (make -C tools values): do not edit. FIZZ's 110 sound values as\n");
    printf("// its own pages name and show them: [name, min, max, default, rule, exceptions | texts]; rule \"int\", \"ofs\" (+n),\n");
    printf("// \"fix2\" / \"fix2s\" (hundredths), \"list\" (the texts, min first); ALGOS: each algorithm's operators (C A B1 B2) as\n");
    printf("// [modulators of each (bit 0 C .. 3 B2), the feedback operator, the X outputs, the Y outputs]; DEST_ORDER: the LFO\n");
    printf("// destinations in the editor's order.\n");
    printf("export const VALUES = [\n");
    for (i = 0; i < QD_QUAD_NP; i++) {
        int16_t mn, mx, df;
        char buf[16], want[16];
        const char *rule = 0;
        int best = -1, bestn = 1 << 30;
        if (!qd_quad_value_range(i, &mn, &mx, &df)) {
            fprintf(stderr, "gen_values: value %d has no range\n", i);
            return 1;
        }
        for (k = 0; k < 4; k++) {               /* the rule with the fewest exceptions */
            int n = 0;
            for (v = mn; v <= mx; v++) {
                qd_quad_value_text(i, v, buf);
                rule_text(RULES[k], v, want);
                n += strcmp(buf, want) != 0;
            }
            if (n < bestn)
                bestn = n, best = k;
        }
        rule = bestn > 8 && mx - mn < 256 ? "list" : RULES[best];
        printf("  [");
        js_str(qd_quad_value_name(i));
        printf(", %d, %d, %d, \"%s\", ", mn, mx, df, rule);
        if (!strcmp(rule, "list")) {
            printf("[");
            for (v = mn; v <= mx; v++) {
                js_str(qd_quad_value_text(i, v, buf));
                if (v < mx)
                    putchar(',');
            }
            printf("]");
        } else {
            if (bestn > 64) {
                fprintf(stderr, "gen_values: value %d (%s): %d texts off its best rule %s\n", i, qd_quad_value_name(i), bestn,
                        rule);
                return 1;
            }
            printf("{");
            for (v = mn, k = 0; v <= mx; v++) {
                qd_quad_value_text(i, v, buf);
                rule_text(rule, v, want);
                if (strcmp(buf, want)) {
                    printf("%s\"%d\":", k++ ? "," : "", v);
                    js_str(buf);
                }
            }
            printf("}");
        }
        printf("],  // %d\n", i);
    }
    printf("];\n");
    printf("export const ALGOS = [\n");
    for (a = 1; a <= 8; a++) {
        uint8_t m[4];
        int fb, ox, oy;
        qd_quad_algo(a, m, &fb, &ox, &oy);
        printf("  [[%d, %d, %d, %d], %d, %d, %d],\n", m[0], m[1], m[2], m[3], fb, ox, oy);
    }
    printf("];\n");
    {   /* the LFO destinations, the editor's order (qd_quad_dest_step from NONE) */
        int d = 0, n = qd_quad_ndest();
        printf("export const DEST_ORDER = [0");
        for (k = 1; k < n; k++) {
            const int e = qd_quad_dest_step(d, 1);
            if (e == d)
                break;
            printf(", %d", e);
            d = e;
        }
        printf("];\n");
    }
    return 0;
}

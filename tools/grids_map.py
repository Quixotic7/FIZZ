"""FIZZ's GRIDS map (docs/TRACK-TOOLS-PLAN.md §4.5), clean-room: 3 x 3 nodes x 3 parts x 32 steps of levels 0..255,
built here from stated rules (no other map read or consulted). Writes core/seq/grids_map.h.

  python3 tools/grids_map.py            write the header
  python3 tools/grids_map.py --check    exit 1 unless the header is what the rules make, byte for byte

The rules (the owner tunes them by ear, then runs this again):
  - a METRIC WEIGHT a step: the bar's downbeat > the half bar > the beats > the 8ths > the 16ths;
  - PART ROLES: LOW (kick-like) leans on the downbeats and the beat before the half bar, MID (snare-like) on the
    backbeats (steps 4 and 12 of 16), HIGH (hats) on the off-beat 8ths and the 16ths;
  - X is SYNCOPATION: going right moves weight from the on-beats to the steps just before them (the anticipations);
  - Y is BUSYNESS: going up lifts the weak 16ths and adds a fixed, per-node variation (a small LCG), so a node up
    there is busier and less regular;
  - the second half of the 32 steps repeats the first with a fill-like lift on its last beat."""
import os
import sys

STEPS, PARTS, NODES = 32, 3, 3


def metric(s):
    k = s % 16
    if k == 0:
        return 255
    if k == 8:
        return 200
    if k % 4 == 0:
        return 150
    if k % 2 == 0:
        return 90
    return 40


def level(nx, ny, part, s):
    k = s % 16
    m = metric(s)
    if part == 0:                                        # LOW: downbeats, the beat before the half bar
        v = m if k % 4 == 0 else m // 3
        if k == 6 or k == 10:
            v += 60
    elif part == 1:                                      # MID: the backbeats
        v = 255 if k in (4, 12) else m // 3
        if k in (7, 15):
            v += 40
    else:                                                # HIGH: off-beat 8ths, the 16ths
        v = 210 if k % 4 == 2 else 120 if k % 2 else m // 2
    if k % 4 == 3 or k % 4 == 1:                         # X: the anticipations rise ..
        v += nx * 55
    elif k % 4 == 0 and k:                               # .. the on-beats (not the bar's one) give way
        v -= nx * 35
    if k % 2:                                            # Y: the weak 16ths lift ..
        v += ny * 45
    seed = (nx * 7 + ny * 13 + part * 29 + s * 31 + 17) & 0xFFFF   # .. and a node's own variation
    for _ in range(3):
        seed = (seed * 25173 + 13849) & 0xFFFF
    v += ((seed >> 8) % 41 - 20) * ny
    if s >= 28:                                          # the 32 steps' last beat: a fill's lift
        v += 30 + 15 * ny
    return max(0, min(255, v))


def header():
    out = ["/* SPDX-License-Identifier: MPL-2.0",
           " * This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of the MPL was not",
           " * distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/. */",
           "/* generated by tools/grids_map.py from its rules (FIZZ's own map, clean-room): do not edit; edit the rules and run",
           " * it again. QD_GRIDS_MAP[x][y][part][step]: x 0..2 the syncopation, y 0..2 the busyness, part 0 LOW 1 MID 2 HIGH */",
           "#pragma once",
           "#include <stdint.h>",
           "",
           "static const uint8_t QD_GRIDS_MAP[3][3][3][32] = {"]
    for nx in range(NODES):
        out.append("    {")
        for ny in range(NODES):
            out.append("        {")
            for p in range(PARTS):
                vals = ", ".join(str(level(nx, ny, p, s)) for s in range(STEPS))
                out.append("            {" + vals + "},")
            out.append("        },")
        out.append("    },")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core", "seq", "grids_map.h")
    text = header()
    if "--check" in sys.argv:
        try:
            with open(path) as f:
                same = f.read() == text
        except OSError:
            same = False
        print("grids_map.h: " + ("as the rules make it" if same else "NOT what the rules make (run tools/grids_map.py)"))
        return 0 if same else 1
    with open(path, "w") as f:
        f.write(text)
    print("wrote " + os.path.normpath(path))
    return 0


if __name__ == "__main__":
    sys.exit(main())

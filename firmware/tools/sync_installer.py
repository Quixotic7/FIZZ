"""fm1-base's web installer code into FIZZ's install page (site/install/), from the submodule as it is checked out.

  firmware/tools/sync_installer.py            write site/install/fm1lib.js (and backup/index.html, see below)
  firmware/tools/sync_installer.py --check    exit 1 if they differ from what the submodule makes (release.py runs it)

site/install/fm1lib.js is fm1-base's web/fm1pkg.js and web/fm1ota.js exactly as fm1-base's tools/make_site.py inlines
them in its installer page (strip_module: no import, no export), with their names exported for FIZZ's page, which is
a module (site/install/install.js). Their MPL-2.0 headers and copyright lines stay in it. Nothing in it is FIZZ's.

When firmware/app/fm1.toml has backup = true, fm1-base's backup page (web/backup/index.html, filled in by make_site.py's
tool_pages from app.h's APP_BACKUP_MAGIC and APP_BACKUP_VERSION) is written to site/install/backup/index.html too, and
the install page links to it. FIZZ is built with backup = false today, so there is none."""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
BASE = REPO / "firmware" / "fm1-base"
APP = REPO / "firmware" / "app"
OUT = REPO / "site" / "install"

# the names the page uses: fm1pkg.js's exports, fm1ota.js's exports and the helpers it keeps to itself
NAMES = ["productOf", "logicalImage", "ufwEntries", "pack7", "unpack7", "Updater", "IS_OTA", "IS_STOCK", "frame",
         "response", "parseRequest", "fail"]


def make():
    """{path: text} of the files this makes"""
    sys.path.insert(0, str(BASE / "tools"))
    import make_site                                    # noqa: E402  (fm1-base's: strip_module, tool_pages)
    commit = subprocess.run(["git", "-C", str(BASE), "rev-parse", "HEAD"], capture_output=True, text=True,
                            check=True).stdout.strip()
    lib = ("// SPDX-License-Identifier: MPL-2.0\n"
           "// Generated by firmware/tools/sync_installer.py from fm1-base " + commit[:12] + " (do not edit): its\n"
           "// web/fm1pkg.js and web/fm1ota.js as its tools/make_site.py inlines them in its installer page, with their\n"
           "// names exported for FIZZ's install page (site/install/install.js). Their own headers follow.\n\n" +
           make_site.strip_module((BASE / "web" / "fm1pkg.js").read_text(encoding="utf-8")) + "\n" +
           make_site.strip_module((BASE / "web" / "fm1ota.js").read_text(encoding="utf-8")) +
           "\nexport { " + ", ".join(NAMES) + " };\n")
    out = {OUT / "fm1lib.js": lib}
    for rel, html in make_site.tool_pages(APP).items():   # (backup = true: backup/index.html; mirror is not offered)
        if rel.startswith("backup/"):
            out[OUT / rel] = html
    return out


def main():
    check = "--check" in sys.argv[1:]
    if not (BASE / "web" / "fm1ota.js").exists():
        raise SystemExit(f"no {BASE}/web/fm1ota.js: git submodule update --init firmware/fm1-base")
    bad = []
    for path, text in make().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        if check:
            bad.append(str(path.relative_to(REPO)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
    if check and bad:
        print("not what fm1-base makes: " + ", ".join(bad) + " (run firmware/tools/sync_installer.py and commit)")
        return 1
    if check:
        print("site/install: fm1-base's installer code as the submodule has it")
    return 0


if __name__ == "__main__":
    sys.exit(main())

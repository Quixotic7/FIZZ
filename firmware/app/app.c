static void fz_audio_on_again(uint32_t f)
{
    (void)f;
    if (fz_mask_depth && !--fz_mask_depth) {
        fm1_irq_off();
        fm1_irq_unmask(FM1_IRQ_ALNK0);
        fm1_irq_on();
    }
}

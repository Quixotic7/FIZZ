static void fz_sample(void)              /* the panel's changes since the last look, queued (FM1VST's order: the buttons
                                          * pressed before the keys, the buttons let go after them) */
{
    const uint32_t b = plat_buttons() & ((1u << NB) - 1u), k = plat_keys(), db = b ^ fz_seen_btn,
                   dk = k ^ fz_seen_keys, ms = plat_ms();
    uint32_t i;
    if (!db && !dk)
        return;
    for (i = 0; i < NB; i++)
        if ((db >> i & 1u) && (b >> i & 1u))
            fz_ev_put(0x8000u | i, ms);
    for (i = 0; i < NKEYS; i++)
        if (dk >> i & 1u)
            fz_ev_put((k >> i & 1u ? 0x8000u : 0u) | 0x100u | i, ms);
    for (i = 0; i < NB; i++)
        if ((db >> i & 1u) && !(b >> i & 1u))
            fz_ev_put(i, ms);
    fz_seen_btn = b;
    fz_seen_keys = k;
}

static void fz_tick_to(uint32_t ms)      /* FIZZ's clock up to ms (P2.10: the core's two halves) */
{
    uint32_t f, t0;
    if ((int32_t)(ms - fz_ticked) <= 0)
        return;
    t0 = plat_ticks24();
    fz_tick_ms += ms - fz_ticked;        /* (P2.15j: the clock's work, for the frames' phases) */
    f = fz_lock();                       /* what the audio side shares: once, over every ms since (coalesced) */
    fz_tick_locked(ms);
    fz_unlock(f, FZ_LOCK_TICK);
    fz_ticked = ms;
    fz_tick_free();                      /* the looks, the store's next job, SysEx's labels: no lock, a ms at a time */
    fz_tick_ticks += plat_ticks24() - t0;
}

static uint8_t fz_sx_buf[1024];          /* a reply (fizz_sx.h QD_SX_FRAME_MAX) */
static void fz_xfer_rx(int inframe, int bulk)   /* a FIZZ frame came (the pacing's window; the counters); only one
                                          * that can be bulk (FZBR, STORE / STORE6, LIST, DUMP) counts: a PARAM never */
{
    uint32_t *x = fz_sx_xs();
    if (!bulk)
        return;
    const uint32_t t = plat_ticks24(), d = (t - x[FZ_XS_T_RX]) / PLAT_TICKS_PER_US;
    x[FZ_XS_RUN] = fz_sx_last() && plat_ms() - fz_sx_last() < FZ_XFER_HOLD_MS ? x[FZ_XS_RUN] + 1u : 1u;
    if ((x[FZ_XS_RUN] >= 3u || fz_sx_bulk()) && x[FZ_XS_T_RX]) {
        x[FZ_XS_RX]++;
        x[FZ_XS_GAP_SUM] += d;
        if (d > x[FZ_XS_GAP_MAX])
            x[FZ_XS_GAP_MAX] = d;
    }
    x[FZ_XS_RX_INFRAME] += inframe != 0;
    x[FZ_XS_T_RX] = t | 1u;
    fz_sx_mark(plat_ms());
}

    FZ_LINE_START(c, line);
    c = fz_put_u(c, FZN_over_halves, fz_over);
    c = fz_put_u(c, FZN_sheds, fz_sheds);
    c = fz_put_u(c, FZN_ramp, fz_ramp);
    c = fz_put_u(c, FZN_gain_q12, (uint32_t)fz_gain);

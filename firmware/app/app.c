static void fz_input(void)               /* everything that changes FIZZ on the main loop, in time order */
{
    const uint32_t t0 = plat_ticks24();
    int r;
#if QD_PKG_BLE
    fz_ble_give();                       /* (between a frame's bands, the scan's wait, the passes: Bluetooth's turn) */
    FZ_PH(FZ_PH_INPUT);
#endif
    fz_sample();
#if QD_PKG_BLE
    fz_bsx_hold();                       /* (Bluetooth's: fz_bsx) */
#endif
#ifndef PLAT_HOST
    fz_hq_hold();                        /* FIZZ's own SysEx out of fm1-base's one slot at once (fz_hq) .. */
    fz_hq_serve(fz_in_frame, 1);         /* .. served in order: between a frame's bands, only the light ones */
#endif
    for (;;) {
        const int ev = fz_ev_r != fz_ev_w, mi = fz_mq_r != fz_mq_w;
        uint32_t f;
        if (!ev && !mi)
            break;
        FZ_BARRIER();
        if (ev && (!mi || (int32_t)(fz_evq_ms[fz_ev_r % FZ_EVQ] - fz_mq_ms[fz_mq_r % FZ_MQ]) <= 0)) {
            const uint32_t e = fz_evq[fz_ev_r % FZ_EVQ], i = e & 0xFFu, down = e >> 15;
            fz_tick_to(fz_evq_ms[fz_ev_r % FZ_EVQ]);
            fz_input_prepare();
            f = fz_lock();
            if (e & 0x100u)
                fz_key((int)i, (int)down, down ? FZ_VEL : 0);
            else
                fz_button((int)i, (int)down);
            fz_unlock(f, FZ_LOCK_EVENT);
            fz_ev_r++;
            fz_touch_ms = plat_ms();
        } else {
            const uint32_t p = fz_mq_pkt[fz_mq_r % FZ_MQ];
            fz_tick_to(fz_mq_ms[fz_mq_r % FZ_MQ]);
            fz_input_prepare();
            f = fz_lock();
            fz_midi_ui((int)(p >> 8 & 0xFFu), (int)(p >> 16 & 0x7Fu), (int)(p >> 24 & 0x7Fu));
            fz_unlock(f, FZ_LOCK_MIDI);
            FZ_BARRIER();
            fz_mq_r++;
        }
    }
    {   /* (P2.10) the clock to now: its locked half coalesced (one call whatever the gap), its free half the core's
         * cheap looks a ms each: a slow frame no longer costs the next one a catch-up under the lock */
        const uint32_t now = plat_ms(), lag = now - fz_ticked;
        if ((int32_t)lag > 0 && lag > fz_tick_lag_max)
            fz_tick_lag_max = lag;
        fz_tick_to(now);
    }
    for (r = 0; r < NE; r++) {
        const int32_t d = plat_enc(r);
        if (d) {
            uint32_t f;
            fz_input_prepare();
            f = fz_lock();
            fz_knob(r, (int)d);
            fz_unlock(f, FZ_LOCK_KNOB);
            fz_touch_ms = plat_ms();
        }
    }
    fz_sysex_out();
    fz_prof.input += plat_ticks24() - t0;
}


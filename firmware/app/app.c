/* (P2.15c) the stats lines' formatter, bounded: FZ_LINE_START sets the line's buffer; a field that would not fit is
 * left out and counted (fz_line_cut), never written past the buffer (P2.15b's line 7 outgrew its 640 bytes and broke
 * the stack: the unit restarted on its watchdog). fz_need: the line's worst-case length, every number at its widest
 * (20 digits); the host test checks it against FZ_LINE for every line */
#define FZ_LINE 1024u
#define FZ_LINE_START(c, buf) ((c) = (buf), fz_lim = (buf) + sizeof(buf) - 1u, fz_need = 0u)
static char *fz_lim;
static uint32_t fz_need, fz_line_cut, fz_line_need[16];
static char *fz_put_us(char *q, const char *label, uint64_t v)   /* a run-time label (part 3's "s1.2=", ""), the number */
{
    char t[24];
    int n = 0;
    uint32_t l = 0;
    while (label[l])
        l++;
    fz_need += l + 21u;
    if (!fz_lim || q + l + 21u > fz_lim) {
        fz_line_cut++;
        return q;
    }
    while (*label)
        *q++ = *label++;
    do
        t[n++] = (char)('0' + (int)(v % 10u));
    while ((v /= 10u) && n < 23);
    while (n)
        *q++ = t[--n];
    *q++ = ' ';
    return q;
}
/* 2026-10-26 (the flash diet): a field is "<id>:<value> " on the wire, FZN_MORE ",<value> " (a list's next), FZN_NONE the
 * number alone; the names live in firmware/app/fz_stats_names.h (the enum, generated) and firmware/tools/
 * fizz_stats_names.py (what fizz_xdata.py prints), both from tools/gen_stats_names.py over this file */
static char *fz_put_u(char *q, int id, uint64_t v)
{
    char lab[8];
    int n = 0;
    if (id == FZN_MORE)
        lab[n++] = ',';
    else if (id != FZN_NONE) {
        char d[4];
        int m = 0, x = id;
        do
            d[m++] = (char)('0' + x % 10);
        while ((x /= 10) && m < 3);
        while (m)
            lab[n++] = d[--m];
        lab[n++] = ':';
    }
    lab[n] = 0;
    return fz_put_us(q, lab, v);
}
static char *fz_put_ws(char *q, const char *label, uint32_t v)   /* (a 32-bit number: its widest is 10 digits) */
{
    char *r = fz_put_us(q, label, v);
    fz_need -= 10u;                      /* (fz_put_us counted 20) */
    return r;
}
static char *fz_put_w(char *q, int id, uint32_t v)
{
    char *r = fz_put_u(q, id, v);
    fz_need -= 10u;
    return r;
}
static void fz_stats_send(int part, const char *line)   /* F0 7D 46 50 part ASCII F7 */
{
    uint8_t f[FZ_LINE + 8u], *q = f;
    if (part >= 0 && part < 16)
        fz_line_need[part] = fz_need;    /* (the host test: every line's worst case within FZ_LINE) */
    *q++ = 0xF0, *q++ = 0x7D, *q++ = 0x46, *q++ = 0x50, *q++ = (uint8_t)part;
    for (; *line && q < f + sizeof f - 1u; line++)
        *q++ = (uint8_t)(*line & 0x7F);
    *q++ = 0xF7;
#ifdef PLAT_HOST
    printf("  stats %d: %.*s\n", part, (int)(q - f - 6), (const char *)f + 5);   /* (no USB: shown) */
#endif
    fz_sx_send(f, (uint32_t)(q - f));
}


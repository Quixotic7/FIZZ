/* (P2.15j) a counted frame's time by phase (ticks, summed since the counters' reset: 7D 46 50 7F, so one screen can be
 * sampled alone): the instant (latch), the bands painted, the input between steps, the send's wait for the scan (its
 * own input runs meanwhile), the send's transfer, and inside all of these the audio interrupt's time and the clock's
 * catch-up (fz_tick_to: its ms and time). Stats line 15 */
static uint32_t fz_fb_work;              /* (P2.16a: the last frame's latch + paint, ticks: the pace's measure) */
static int fz_draw_fb(int all)           /* a frame: drawn at one instant into the rows, the changed ones sent; 1 drawn */
{
    const uint32_t t0 = plat_ticks24();
    uint32_t bands = 0, gen = fz_pal_gen, t1, d, ph_latch = 0, ph_paint = 0, ph_input = 0;
    const uint32_t isr0 = (uint32_t)fz_prof.isr_in_frame, tick0 = fz_tick_ticks, tms0 = fz_tick_ms,
                   wait0 = fz_fb.wait_sum_us, span0 = fz_fb.span_sum_us;
    if (!fz_fb_on)
        return 0;
    fz_in_frame = 1;
    if (FZ_FB_FULL_EVERY && ++fz_fb_n % (FZ_FB_FULL_EVERY ? FZ_FB_FULL_EVERY : 1u) == 0u)   /* (0: the core's band check alone) */
        fz_fb_attach(fz_rowp);           /* (every band drawn: FZ_FB_FULL_EVERY) */
    {   /* (P2.15) the frame from one instant, drawn FZ_FB_STEP bands at a time with the input (the panel, MIDI, the
         * clock, the LEDs) between: a heavy frame no longer holds a press back for its whole drawing */
        uint32_t ti = 0, tl, k;
        FZ_PH(FZ_PH_LATCH);
        if (fz_frame_fb_begin(&bands)) {
            FZ_GIVE();                   /* (the Bluetooth package: its turn between the instant and the first band) */
            tl = plat_ticks24();
            fz_fbs.latch += tl - t0;     /* (the instant: the screen's logic once, its drawing calls recorded) */
            for (k = 0; k < 32u; k++)
                fz_fbs.bands += bands >> k & 1u;
            fz_fbs.frames++;
            while ((FZ_PH(FZ_PH_PAINT), fz_frame_fb_step(FZ_FB_STEP)) > 0) {
                const uint32_t tq = plat_ticks24();
                fz_input();
                if (plat_ms() - fz_led_t >= FZ_LED_MS)
                    fz_lights();
                ti += plat_ticks24() - tq;
                fz_fbs.steps++;
            }
            fz_fbs.paint += plat_ticks24() - tl - ti;   /* (the bands drawn from the recording) */
            ph_latch = tl - t0, ph_paint = plat_ticks24() - tl - ti, ph_input = ti;
            fz_fb_work = ph_latch + ph_paint;   /* (P2.16a: not the scan's wait, the input, the send) */
        } else {
            fz_fbs.latch_only += plat_ticks24() - t0;    /* (looked at, nothing changed) */
            fz_fbs.looks_same++;
        }
        t1 = plat_ticks24();
        fz_prof.draw += t1 - t0 - ti;
        fz_prof.input_in_frame += ti;
        fz_fbs.input += ti;
    }
    fz_pal = fz_fb_palette(&gen);
    if (gen != fz_pal_gen)
        all = 1, fz_pal_gen = gen;       /* (a new palette: every row again) */
    if (bands || all) {
        const uint32_t n = fz_fb_send(fz_rowp, fz_pal, all ? 0xFFFFFFFFu : bands, 16u, all);   /* (16: QD_FB_BAND) */
        fz_rows_sent += n;
        if (!n && !all)
            bands = 0;                   /* (drawn, nothing changed on the screen: not a frame, not animating) */
    }
    fz_prof.lcd += plat_ticks24() - t1;
    fz_in_frame = 0;
#ifdef PLAT_HOST
    {   /* (the host's check: the panel holds every row's colours as sent) */
        uint32_t y, x, n = 0;
        for (y = 0; y < 240u; y++)
            for (x = 0; x < 240u; x++)
                if (fb[y * 240u + x] != fz_pal[fz_rowp[y][x]]) {
                    n++;
                    break;
                }
        if (n > fz_host_stale_max)
            fz_host_stale_max = n;
    }
#endif
    if (!bands && !all)
        return 0;
    d = plat_ticks24() - t0;
    fz_prof.frame += d;
    fz_prof.n_frame++;
    if (d > fz_prof.frame_max)
        fz_prof.frame_max = d;
    fz_frames_sent++;
    fz_fp.n++;
    fz_fp.total += d, fz_fp.latch += ph_latch, fz_fp.paint += ph_paint, fz_fp.input += ph_input;
    fz_fp.wait += (uint64_t)(fz_fb.wait_sum_us - wait0) * PLAT_TICKS_PER_US;
    fz_fp.xfer += (uint64_t)(fz_fb.span_sum_us - span0) * PLAT_TICKS_PER_US;
    fz_fp.isr += (uint32_t)fz_prof.isr_in_frame - isr0;
    fz_fp.tick += fz_tick_ticks - tick0;
    fz_fp.tick_ms += fz_tick_ms - tms0;
    {   /* (P2.13: the frame's time by screen, as the strips' build has it) */
        const int sc = fz_screen_index();
        fz_screens[sc].n++;
        fz_screens[sc].sum += d;
        if (d > fz_screens[sc].max)
            fz_screens[sc].max = d;
    }
    return 1;
}

            c = fz_put_u(c, FZN_rest_begin_us, fz_us(beg / ni));
            c = fz_put_u(c, FZN_rest_voices_call_us, fz_us(vb / ni));
            c = fz_put_u(c, FZN_rest_end_us, fz_us(en / ni));
            c = fz_put_u(c, FZN_rest_out_us, fz_us(fz_prof.a_out / ni));

#!/usr/bin/env python3
"""The SENDS cat's parts from the owner's vector (art/cat-sends.svg) and today's SENDS screens from the simulator.

    python3 mockups/make_cat_svg.py [--shots]

Writes mockups/fizz-sends-cat-svg.js: each drawn path of the SVG (its d, fill, stroke, width, translate, bounds) named
by its part. With --shots, also runs the host simulator (firmware/app/build/host/fizz_host, build it with
firmware/build.py --host) on mockups/ref/sends-real.txt and copies its eight screens to mockups/ref/sends-real-N.png:
the mock-up draws the cat over their bars, so the header, the labels, the values and the steps are the firmware's own.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
SVG = os.path.join(REPO, 'art', 'cat-sends.svg')
# the drawn paths in the SVG's order (after the black backdrop), as the owner drew them
NAMES = ['outline', 'visor_frame', 'visor_lens', 'ear_l', None, 'ear_r',
         'wh_l1', 'wh_l2', 'wh_l3', 'wh_r1', 'wh_r2', 'wh_r3', 'nose', 'mouth1', 'mouth2']

s = open(SVG).read()
body = s[s.index('</defs>'):]
paths = re.findall(r'<path\s([^>]*)/>', body)[1:]          # [0] is the black backdrop
assert len(paths) == len(NAMES), len(paths)


def attr(a, k):
    m = re.search(r'\b%s="([^"]*)"' % k, a)
    return m.group(1) if m else None


parts = []
for name, a in zip(NAMES, paths):
    if not name:
        continue
    d = attr(a, 'd')
    tx = ty = 0.0
    t = attr(a, 'transform')
    if t:
        m = [float(x) for x in re.findall(r'-?[\d.]+', t)]
        tx, ty = m[4], m[5]
    nums = [float(x) for x in re.findall(r'-?\d+(?:\.\d+)?(?:e-?\d+)?', d)]
    xs, ys = [x + tx for x in nums[0::2]], [y + ty for y in nums[1::2]]
    parts.append(dict(name=name, d=d, fill=attr(a, 'fill'), stroke=attr(a, 'stroke'), sw=float(attr(a, 'stroke-width') or 0),
                      tx=tx, ty=ty, box=[round(min(xs), 1), round(min(ys), 1), round(max(xs), 1), round(max(ys), 1)]))

out = ['// generated by make_cat_svg.py from art/CatSendUI_002.svg: the SENDS cat\'s parts (the SVG\'s units, 1050 x 917)',
       'const CAT_PARTS = {']
for p in parts:
    out.append("  %s: {d: '%s', fill: %s, stroke: %s, sw: %g, tx: %g, ty: %g, box: %s}," % (
        p['name'], p['d'], repr(p['fill']) if p['fill'] not in (None, 'none') else 'null',
        repr(p['stroke']) if p['stroke'] else 'null', p['sw'], p['tx'], p['ty'], p['box']))
out.append('};')
open(os.path.join(HERE, 'fizz-sends-cat-svg.js'), 'w').write('\n'.join(out) + '\n')
print('parts:', ', '.join(p['name'] for p in parts))

if '--shots' in sys.argv:
    tmp = tempfile.mkdtemp()
    subprocess.run([os.path.join(REPO, 'firmware/app/build/host/fizz_host'), os.path.join(HERE, 'ref', 'sends-real.txt'), tmp], check=True)
    for i in range(1, 9):
        shutil.copy(os.path.join(tmp, 's%d.png' % i), os.path.join(HERE, 'ref', 'sends-real-%d.png' % i))
    print('shots: mockups/ref/sends-real-1..8.png')
